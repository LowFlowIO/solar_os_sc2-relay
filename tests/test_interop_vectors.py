import json
import os

import sc2ref
from helpers import Conn, Device, relay_server, run
from sc2_relay import crypto
from sc2proto import b64d, frames

HERE = os.path.dirname(os.path.abspath(__file__))
VEC = json.load(open(os.path.join(HERE, "data", "sc2_vectors.json")))
F = VEC["frames"]


def device_from_rng(hex_rng):
    d = Device()
    d.ident = sc2ref.Identity(sc2ref.Rng(bytes.fromhex(hex_rng) + bytes(4096)))
    d.id = d.ident.id.hex()
    return d


def test_relay_signature_check_matches_strict_vectors():
    for v in VEC["ed25519_verify"]:
        got = crypto.verify(bytes.fromhex(v["pk"]), bytes.fromhex(v["msg"]), bytes.fromhex(v["sig"]))
        assert got == v["ok"], v["note"]


def test_room_send_vector_signature_as_the_relay_checks_it():
    send = json.loads(F["room_send"])
    env = frames.validate_room_env(send["env"])
    ik = bytes.fromhex(VEC["room"]["ik_pub"])
    msg = frames.room_env_signed_bytes(send["room"], env)
    assert crypto.verify(ik, msg, b64d(env["sig"]))
    assert not crypto.verify(ik, frames.room_env_signed_bytes(send["room"], dict(env, n=env["n"] + 1)),
                             b64d(env["sig"]))
    # relay fan-out frame layout equals the C vector
    out = {"type": "room.msg", "room": send["room"], "seq": "4523", "env": env}
    assert sc2ref.dumps(out) == F["room_msg"]


def test_c_public_post_vector_through_the_relay():
    async def body():
        async with relay_server(relay_id="relay.example") as srv:
            port = srv.ports["plain"]
            ana = Device(seed=bytes.fromhex(F["post_seed"]))
            reader = Device()
            await ana.connect(port)
            await reader.connect(port)
            await ana.join("pub:general")
            await reader.join("pub:general")
            line = F["room_post"]
            await ana.conn.send(line)
            ack = await ana.conn.expect("ack")
            assert ack == {"type": "ack", "rid": "p1", "seq": "1"}
            await reader.conn.send({"type": "ping", "rid": "x"})
            raw = await asyncio_readline_until(reader.conn, b'"room.pub"')
            # byte-for-byte: the relay forwards the C post unchanged (UTF-8 kept)
            assert raw.decode().rstrip("\n") == F["room_pub"].replace('"seq":"99813"', '"seq":"1"')
            await ana.conn.send(F["room_post_del"])
            ack = await ana.conn.expect("ack")
            assert ack["seq"] == "2"
            # ASCII-escaped variant of the same post is the same JSON value
            assert json.loads(F["room_pub_ascii"])["post"] == json.loads(F["room_pub"])["post"]
    run(body())


async def asyncio_readline_until(conn, needle):
    import asyncio
    while True:
        line = await asyncio.wait_for(conn.reader.readline(), 5)
        if needle in line:
            return line


def test_c_dm_vector_through_the_relay():
    async def body():
        async with relay_server(relay_id="relay.example") as srv:
            port = srv.ports["plain"]
            alice = device_from_rng(VEC["ratchet"]["alice_rng"])
            bob = device_from_rng(VEC["ratchet"]["bob_rng"])
            send = json.loads(F["dm_send"])
            assert alice.id == send["env"]["from"] and bob.id == send["to"]
